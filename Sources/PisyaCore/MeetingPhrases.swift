/// Локальный генератор фраз для созвонов.
public struct MeetingPhraseGenerator {
    struct Group {
        let actions: [String]
        let objects: [String]
    }

    private var previous: String?
    private var curatedDeck: [String] = []
    private var lastCurated: String?
    public init() {}

    public mutating func next() -> String {
        for _ in 0..<16 {
            let phrase: String
            if Int.random(in: 0..<4) != 0 {
                phrase = nextCurated()
            } else {
                let group = Self.groups.randomElement()!
                let opening = Self.openings.randomElement()!
                let ending = Self.endings.randomElement()!
                guard Self.isCompatible(opening: opening, ending: ending) else { continue }
                phrase = Self.compose(
                    opening: opening,
                    lead: Self.leads.randomElement()!,
                    action: group.actions.randomElement()!,
                    object: group.objects.randomElement()!,
                    ending: ending
                )
            }
            if phrase != previous && phrase.count >= 75 && phrase.split(whereSeparator: \.isWhitespace).count >= 10 {
                previous = phrase
                return phrase
            }
        }
        let opening = previous?.hasPrefix(Self.openings[0] + " ") == true ? Self.openings[1] : Self.openings[0]
        let fallback = Self.compose(opening: opening, lead: "нам нужно", action: "обсудить", object: "воронку согласований", ending: "чтобы у всех сложилась единая картинка")
        previous = fallback
        return fallback
    }

    mutating func nextCurated() -> String {
        if curatedDeck.isEmpty {
            curatedDeck = Self.curated.shuffled()
            if curatedDeck.count > 1 && curatedDeck.last == lastCurated {
                curatedDeck.swapAt(0, curatedDeck.count - 1)
            }
        }
        let phrase = curatedDeck.removeLast()
        lastCurated = phrase
        return phrase
    }

    static func isCompatible(opening: String, ending: String) -> Bool {
        let start = opening.lowercased()
        return !(["чтобы", "прежде чем"].contains { start.hasPrefix($0) && ending.hasPrefix($0) })
    }

    static func compose(opening: String, lead: String, action: String, object: String, ending: String) -> String {
        "\(opening) \(lead) \(action) \(object), \(ending)"
    }

