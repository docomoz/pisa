/// Локальный генератор фраз для созвонов.
public struct MeetingPhraseGenerator {
    private var previous: String?

    public init() {}

    public mutating func next() -> String {
        for _ in 0..<4 {
            let phrase = Self.makePhrase()
            if phrase != previous {
                previous = phrase
                return phrase
            }
        }
        // Even an unlucky sequence of random choices must produce a new phrase.
        let opening = previous?.hasPrefix(Self.openings[0] + " ") == true
            ? Self.openings[1] : Self.openings[0]
        let fallback = Self.format(opening, Self.actions[0], Self.objects[0], Self.endings[0])
        previous = fallback
        return fallback
    }

    private static func makePhrase() -> String {
        if Int.random(in: 0..<5) == 0 {
            return displayText(asides.randomElement()!)
        }
        let opening = openings.randomElement()!
        let action = actions.randomElement()!
        // The original site also has actions ending in «по», which require a
        // different grammatical case. Indeclinable terms work with both forms.
        let object = (action.hasSuffix(" по") ? indeclinableObjects : objects).randomElement()!
        return format(opening, action, object, endings.randomElement()!)
    }

    private static func format(_ opening: String, _ action: String, _ object: String, _ ending: String) -> String {
        let phrase = "\(opening) \(action) \(object), \(ending)"
        // Isolated one-sentence UI text has no final full stop; multi-sentence
        // phrases keep the punctuation from the original site.
        return displayText(phrase)
    }

    static func displayText(_ text: String) -> String {
        guard text.hasSuffix("."), !text.contains(". ") else { return text }
        return String(text.dropLast())
    }

